export function buildFixture(): Fixture {
  return {
    _comment:
      'Generated by scripts/export-theme-fixture.ts from seed/src/data/content.ts defaultTheme. Do not edit by hand; run `npm run fixture`.',
    themes: {
      default: { ...defaultTheme },
      [NORTH]: northTheme,
      [SOUTH]: southTheme,
    },
    pages: [northHome, southHome, northDraftOnly],
    contents: [northAnnouncement],
  };
}

export const FIXTURE_OUTPUT = fileURLToPath(new URL('../fixtures/contentools.json', import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(FIXTURE_OUTPUT, `${JSON.stringify(buildFixture(), null, 2)}\n`);
  console.log(`wrote ${FIXTURE_OUTPUT}`);
}
