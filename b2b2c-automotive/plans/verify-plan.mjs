// Verifies the implementation plan of the Malva B2B2C automotive project. No dependencies.
//   node plans/verify-plan.mjs             check only (exit 1 on any error)
//   node plans/verify-plan.mjs --sync      first regenerate the GRAPH and WAVES blocks of DEPENDENCY-PLAN.md,
//                                          the STATUS block of STATUS.md and SPEC-COVERAGE.md; then check
//   node plans/verify-plan.mjs --strict    missing plans/workstreams/<LETTER>-*.md files are errors, not warnings
//
// Checks:
//  - the workstream table of DEPENDENCY-PLAN.md has a row for every letter A-Z, dependencies point only to
//    earlier letters (so there are no cycles), declared "Parallel with" pairs do not depend on each other
//  - every spec dir matching openspec/specs/{consumer-storefront,seller-portal}/(bootstrap-and-structure|theming-design|design-*)
//    is listed in the Implements column of at least one workstream and is primary (first listed) in exactly one
//    (a spec listed in a single workstream is primary there, whatever its position in the list)
//    (a spec whose spec.md carries the marker line <!-- OUT-OF-SCOPE --> is excluded from this requirement,
//    and it is an error to list it in the table)
//  - every spec id used in the table exists on disk
//  - every OA-nn / SO-nn named in the plan exists in TODO-MANUAL-TESTING.md, and all row ids there are unique
//  - plans/workstreams/<LETTER>-*.md exists for each letter (warning unless --strict)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PLANS = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(PLANS);
const SYNC = process.argv.includes('--sync');
const STRICT = process.argv.includes('--strict');
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');
const SPEC_APPS = { cs: 'consumer-storefront', sp: 'seller-portal' };
const OWNED = /^(bootstrap-and-structure|theming-design|design-.+)$/;

const errors = [];
const warnings = [];
const err = (m) => errors.push(m);
const warn = (m) => warnings.push(m);
const read = (p) => readFileSync(p, 'utf8');

const BEGIN = (k) => `<!-- ${k}:BEGIN (generated by plans/verify-plan.mjs --sync) -->`;
const END = (k) => `<!-- ${k}:END -->`;
function blockOf(text, key) {
  const b = text.indexOf(BEGIN(key));
  const e = text.indexOf(END(key));
  return b < 0 || e < 0 ? null : text.slice(b + BEGIN(key).length, e).replace(/^\n|\n$/g, '');
}
function replaceBlock(text, key, body) {
  const b = text.indexOf(BEGIN(key));
  const e = text.indexOf(END(key));
  if (b < 0 || e < 0) return null;
  return `${text.slice(0, b)}${BEGIN(key)}\n${body}\n${text.slice(e)}`;
}

// ---------- specs on disk ----------
const specs = {}; // 'cs/design-x' -> { reqs, scenarios }
const outOfScope = {}; // specs carrying the marker line <!-- OUT-OF-SCOPE -->: kept on disk, not implemented, not required in the table
for (const [short, dir] of Object.entries(SPEC_APPS)) {
  const base = path.join(ROOT, 'openspec/specs', dir);
  if (!existsSync(base)) { err(`missing directory openspec/specs/${dir}`); continue; }
  for (const d of readdirSync(base, { withFileTypes: true })) {
    if (!d.isDirectory() || !OWNED.test(d.name)) continue;
    const f = path.join(base, d.name, 'spec.md');
    if (!existsSync(f)) { err(`openspec/specs/${dir}/${d.name}: no spec.md`); continue; }
    const text = read(f);
    if (/^<!-- OUT-OF-SCOPE -->\s*$/m.test(text)) { outOfScope[`${short}/${d.name}`] = true; continue; }
    specs[`${short}/${d.name}`] = {
      reqs: (text.match(/^### Requirement:/gm) ?? []).length,
      scenarios: (text.match(/^#### Scenario:/gm) ?? []).length,
    };
  }
}

// ---------- workstream table ----------
const planPath = path.join(PLANS, 'DEPENDENCY-PLAN.md');
const planText = read(planPath);
const expand = (s) => {
  const out = new Set();
  for (const part of s.replace(/\*|`|\(.*?\)/g, '').split(',').map((x) => x.trim()).filter(Boolean)) {
    const r = part.match(/^([A-Z])\s*[–-]\s*([A-Z])$/);
    if (r) for (let c = r[1].charCodeAt(0); c <= r[2].charCodeAt(0); c++) out.add(String.fromCharCode(c));
    else if (/^[A-Z]$/.test(part)) out.add(part);
  }
  return out;
};
const table = {};
for (const line of planText.split('\n')) {
  const c = line.split('|').map((x) => x.trim());
  if (c.length >= 8 && /^[A-Z]$/.test(c[1])) {
    const implText = c[3];
    table[c[1]] = {
      name: c[2],
      implText,
      impl: [...implText.matchAll(/\b(cs|sp)\/([a-z0-9-]+)/g)].map((m) => `${m[1]}/${m[2]}`),
      all: /^all$/i.test(implText.trim()),
      deps: expand(c[4]),
      prereqs: c[5],
      parallel: expand(c[6]),
    };
  }
}
for (const L of LETTERS) if (!table[L]) err(`DEPENDENCY-PLAN.md: no table row for workstream ${L}`);
for (const [L, row] of Object.entries(table)) {
  for (const d of row.deps) {
    if (d >= L) err(`DEPENDENCY-PLAN.md: ${L} depends on ${d}, which is not an earlier letter`);
    else if (!table[d]) err(`DEPENDENCY-PLAN.md: ${L} depends on unknown workstream ${d}`);
  }
}

// transitive dependencies (only meaningful once letter order is valid)
const ancestors = {};
const anc = (L, seen = new Set()) => {
  if (ancestors[L]) return ancestors[L];
  const out = new Set();
  for (const d of table[L]?.deps ?? []) if (d < L && !seen.has(d)) { out.add(d); for (const a of anc(d, new Set([...seen, L]))) out.add(a); }
  return (ancestors[L] = out);
};
for (const L of LETTERS) if (table[L]) anc(L);
for (const [L, row] of Object.entries(table)) {
  for (const p of row.parallel) {
    if (!table[p]) { err(`DEPENDENCY-PLAN.md: ${L} is parallel with unknown workstream ${p}`); continue; }
    if (anc(L).has(p) || anc(p).has(L)) warn(`DEPENDENCY-PLAN.md: ${L} is declared parallel with ${p}, but one depends (transitively) on the other`);
    if (!table[p].parallel.has(L)) warn(`DEPENDENCY-PLAN.md: "Parallel with" is not symmetric (${L} lists ${p}, ${p} does not list ${L})`);
  }
}

// ---------- spec coverage ----------
const listed = {}; // spec -> [{ L, first }]
for (const [L, row] of Object.entries(table)) {
  row.impl.forEach((s, i) => {
    if (outOfScope[s]) { err(`DEPENDENCY-PLAN.md: workstream ${L} lists ${s}, which is marked <!-- OUT-OF-SCOPE -->`); return; }
    if (!specs[s]) { err(`DEPENDENCY-PLAN.md: workstream ${L} lists unknown spec ${s}`); return; }
    (listed[s] ??= []).push({ L, first: i === 0 });
  });
}
for (const s of Object.keys(specs)) {
  const l = listed[s] ?? [];
  if (l.length === 0) { err(`spec ${s} is not listed in the Implements column of any workstream`); continue; }
  const primaries = l.length === 1 ? l : l.filter((x) => x.first);
  if (primaries.length !== 1) err(`spec ${s} must be primary (first listed) in exactly one workstream, found ${primaries.length} (listed by ${l.map((x) => x.L).join(', ')})`);
}
const primaryOf = (s) => {
  const l = listed[s] ?? [];
  return (l.length === 1 ? l[0] : l.find((x) => x.first))?.L ?? '';
};

// ---------- workstream files ----------
const wsDir = path.join(PLANS, 'workstreams');
const wsFiles = existsSync(wsDir) ? readdirSync(wsDir).filter((f) => /^[A-Z]-.+\.md$/.test(f)) : [];
const ws = {};
for (const f of wsFiles) ws[f[0]] = read(path.join(wsDir, f));
const missingWs = LETTERS.filter((L) => !ws[L]);
for (const L of missingWs) (STRICT ? err : warn)(`workstreams/: no file ${L}-*.md`);

// ---------- manual testing rows ----------
const todoPath = path.join(PLANS, 'TODO-MANUAL-TESTING.md');
const todo = existsSync(todoPath) ? read(todoPath) : '';
if (!todo) err('TODO-MANUAL-TESTING.md is missing');
const ids = new Map();
for (const line of todo.split('\n')) {
  const m = line.match(/^\|\s*((?:OA|SO)-\d\d|M-[A-Za-z0-9-]+)\s*\|/);
  if (m) ids.set(m[1], (ids.get(m[1]) ?? 0) + 1);
}
for (const [id, n] of ids) if (n > 1) err(`TODO-MANUAL-TESTING.md: row id ${id} appears ${n} times`);
const planRefs = new Set(planText.match(/\b(?:OA|SO)-\d\d\b/g) ?? []);
for (const r of planRefs) if (!ids.has(r)) err(`DEPENDENCY-PLAN.md references ${r}, which has no row in TODO-MANUAL-TESTING.md`);
for (const L of LETTERS) {
  for (const r of new Set(ws[L]?.match(/\b(?:OA|SO)-\d\d\b/g) ?? [])) if (!ids.has(r)) err(`workstreams/${L}-*.md references ${r}, which has no row in TODO-MANUAL-TESTING.md`);
}

// ---------- generated: graph, waves ----------
const level = {};
const lv = (L) => (level[L] ??= [...(table[L]?.deps ?? [])].filter((d) => d < L).reduce((m, d) => Math.max(m, lv(d) + 1), 0));
for (const L of LETTERS) if (table[L]) lv(L);
const label = (L) => `${L} ${(table[L]?.name ?? '').replace(/"/g, "'").slice(0, 44)}`;
const edges = [];
for (const L of LETTERS) for (const d of [...(table[L]?.deps ?? [])].sort()) {
  // Z depends on A-Y: draw only edges from letters nobody else in its dependency list already reaches
  const redundant = [...table[L].deps].some((o) => o !== d && anc(o).has(d));
  if (!redundant) edges.push(`  ${d}["${label(d)}"] --> ${L}["${label(L)}"]`);
}
const graph = '```mermaid\ngraph LR\n' + edges.join('\n') + '\n```\n\nTransitive edges are omitted (an edge is drawn only when no other dependency of the target already reaches the source).';

const byLevel = {};
for (const L of LETTERS) if (table[L]) (byLevel[level[L]] ??= []).push(L);
const waveRows = ['| Wave | Can start when | Workstreams (run in parallel) |', '| --- | --- | --- |'];
for (const w of Object.keys(byLevel).map(Number).sort((a, b) => a - b)) {
  waveRows.push(`| ${w + 1} | ${w === 0 ? 'immediately' : `all of wave ${w} they depend on are Done`} | ${byLevel[w].map((L) => `**${L}** ${table[L].name}`).join('<br>')} |`);
}
const waves = waveRows.join('\n') + '\n\nWaves are topological levels: a workstream sits one wave after its latest dependency. A workstream may start earlier than its wave only if all its own dependencies are Done.';

// ---------- generated: status counts ----------
const statusPath = path.join(PLANS, 'STATUS.md');
const statusText = read(statusPath);
const prevStatus = new Map((blockOf(statusText, 'STATUS') ?? '').split('\n').map((l) => l.split('|').map((c) => c.trim())).filter((c) => /^[A-Z]$/.test(c[1] ?? '')).map((c) => [c[1], c[5]]));
const statusRows = ['| WS | Name | Tasks done/total | Status |', '| --- | --- | --- | --- |'];
let totalTasks = 0;
let doneTasks = 0;
for (const L of LETTERS) {
  const all = [...(ws[L] ?? '').matchAll(/^- \[( |x)\] \**[A-Z]-\d\d\b/gm)];
  const done = all.filter((m) => m[1] === 'x').length;
  totalTasks += all.length;
  doneTasks += done;
  statusRows.push(`| ${L} | ${table[L]?.name ?? ''} | ${ws[L] ? `${done}/${all.length}` : 'no file'} | ${prevStatus.get(L) || 'Not started'} |`);
}
const specTotal = Object.keys(specs).length;
const specCovered = Object.keys(specs).filter((s) => (listed[s] ?? []).length > 0).length;
statusRows.push('', `Workstream files: ${LETTERS.length - missingWs.length}/${LETTERS.length}. Tasks done: ${doneTasks}/${totalTasks}. Specs owned by the plan: ${specTotal}, listed by a workstream: ${specCovered}, out of scope (marker): ${Object.keys(outOfScope).length}. Manual-testing rows: ${ids.size}.`);
const statusBody = statusRows.join('\n');

// ---------- generated: spec coverage ----------
const covRows = [
  '<!-- SPDX-License-Identifier: MIT -->',
  '<!-- Copyright (c) 2026 commercetools GmbH. Freely available, AS IS and UNSUPPORTED. -->',
  '',
  '# Spec coverage',
  '',
  'Generated by `node plans/verify-plan.mjs --sync`; do not edit. `cs/` = `openspec/specs/consumer-storefront/`, `sp/` = `openspec/specs/seller-portal/`.',
  '',
  '| Spec | Requirements | Scenarios | Primary workstream | Other workstreams |',
  '| --- | --- | --- | --- | --- |',
];
let reqSum = 0;
for (const s of Object.keys(specs).sort()) {
  const p = primaryOf(s);
  const others = (listed[s] ?? []).map((x) => x.L).filter((L) => L !== p);
  reqSum += specs[s].reqs;
  covRows.push(`| ${s} | ${specs[s].reqs} | ${specs[s].scenarios} | ${p || 'NONE'} | ${others.join(', ') || '-'} |`);
}
covRows.push('', `${specTotal} specs, ${reqSum} requirements.`, '');
if (Object.keys(outOfScope).length) {
  covRows.push('## Out of scope (marker `<!-- OUT-OF-SCOPE -->` in the spec, owner decision)', '', 'Kept on disk for reference; no workstream implements them and the plan does not require them.', '');
  for (const s of Object.keys(outOfScope).sort()) covRows.push(`- ${s}`);
  covRows.push('');
}
const coverage = covRows.join('\n');

// ---------- write or compare ----------
const covPath = path.join(PLANS, 'SPEC-COVERAGE.md');
function handle(file, text, key, body, label2) {
  if (blockOf(text, key) === null) { err(`${label2}: missing ${key} markers (${BEGIN(key)} ... ${END(key)})`); return; }
  if (SYNC) writeFileSync(file, replaceBlock(text, key, body));
  else if (blockOf(text, key).trim() !== body.trim()) err(`${label2}: ${key} block is stale; run with --sync`);
}
handle(planPath, planText, 'GRAPH', graph, 'DEPENDENCY-PLAN.md');
handle(planPath, SYNC ? read(planPath) : planText, 'WAVES', waves, 'DEPENDENCY-PLAN.md');
handle(statusPath, statusText, 'STATUS', statusBody, 'STATUS.md');
// The part of SPEC-COVERAGE.md from "## Test and evidence coverage" on is written by plans/spec-coverage.mjs and kept as is.
const TAIL = '## Test and evidence coverage';
const covExisting = existsSync(covPath) ? read(covPath) : '';
const covTailAt = covExisting.indexOf(TAIL);
const covTail = covTailAt >= 0 ? covExisting.slice(covTailAt) : '';
const covHead = covTailAt >= 0 ? covExisting.slice(0, covTailAt) : covExisting;
if (SYNC) writeFileSync(covPath, covTail ? `${coverage.replace(/\s*$/, '')}\n\n${covTail}` : coverage);
else if (!existsSync(covPath) || covHead.trim() !== coverage.trim()) err('SPEC-COVERAGE.md is missing or stale; run with --sync');

// ---------- report ----------
if (warnings.length) console.warn(warnings.map((w) => `WARN  ${w}`).join('\n'));
if (errors.length) {
  console.error(errors.map((e) => `ERROR ${e}`).join('\n'));
  console.error(`plan verification: FAILED (${errors.length} error${errors.length > 1 ? 's' : ''}, ${warnings.length} warning${warnings.length === 1 ? '' : 's'})`);
  process.exit(1);
}
console.log(`${LETTERS.length} workstreams, ${specTotal} specs (${reqSum} requirements), ${waves.split('\n').filter((l) => /^\| \d+ /.test(l)).length} waves, ${ids.size} manual-testing rows, ${totalTasks} tasks`);
console.log(`plan verification: OK (${warnings.length} warning${warnings.length === 1 ? '' : 's'})`);
