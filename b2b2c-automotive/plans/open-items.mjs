// Consolidates everything still open into plans/OPEN-ITEMS.md, by who has to act. No dependencies.
//   node plans/open-items.mjs           rewrite plans/OPEN-ITEMS.md
//   node plans/open-items.mjs --check   exit 1 when the file is stale
//
// Sources: plans/TODO-MANUAL-TESTING.md (rows not closed), plans/QUESTIONS.md and plans/notes/questions-*.md (questions
// without an owner answer: the default in the row is in use meanwhile), plans/MISSED-FEATURES.md (rows whose status is
// open or a known gap). It only reads those files; the owner's answers stay where they are.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ownerOf, parseManual, splitRow } from './verify-manual.mjs';

const PLANS = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(p, 'utf8');
const clip = (s, n) => {
  const t = s.replace(/\s+/g, ' ').replace(/\|/g, '/').trim();
  return t.length > n ? `${t.slice(0, n - 1).trimEnd()}...` : t;
};
const plain = (s) => s.replace(/\*\*|~~/g, '');

/** Open questions of one file: rows with an id, at least 4 cells, and no owner answer. */
export function openQuestions(text, source) {
  const out = [];
  let statusCol = -1;
  for (const line of text.split('\n')) {
    if (!line.startsWith('|')) continue;
    const cells = splitRow(line);
    if (cells[0] === 'ID') { statusCol = cells.indexOf('Status'); continue; }
    if (!/^Q-[A-Za-z0-9]+/.test(cells[0] ?? '') || cells.length < 4) continue;
    const first = cells[0];
    const answered = /answered|obsolete|deleted|removed|closed/i.test(first) || /^~~/.test(cells[1] ?? '') || (statusCol >= 0 && cells[statusCol] && !/^open/i.test(cells[statusCol]));
    if (answered) continue;
    out.push({ id: plain(first).split(/\s/)[0], note: plain(first).replace(/^Q-\S+\s*\(?/, '').replace(/\)$/, ''), question: plain(cells[1]), def: plain(cells[2]), blocks: plain(cells[3] ?? ''), source });
  }
  return out;
}

/** MISSED-FEATURES rows still open. */
export function openMissed(text) {
  const out = [];
  for (const line of text.split('\n')) {
    if (!line.startsWith('|')) continue;
    const c = splitRow(line);
    if (c.length < 6 || c[0] === 'Workstream' || /^-+$/.test(c[0])) continue;
    const status = plain(c[c.length - 1]);
    if (!/^(open|known gap)/i.test(status)) continue;
    out.push({ ws: c[0], spec: c[1], what: c[2], needs: c[4], status });
  }
  return out;
}

const needsOwner = (needs) => /\b(owner|OA-\d\d|SO-\d\d|credentials|live project)\b/i.test(needs) && !/^none\b/i.test(needs);

export function build() {
  const todo = parseManual(read(path.join(PLANS, 'TODO-MANUAL-TESTING.md')));
  const open = todo.rows.filter((r) => r.state !== 'closed');
  const detail = new Map();
  for (const line of read(path.join(PLANS, 'TODO-MANUAL-TESTING.md')).split(/^## 4\./m)[0].split('\n')) {
    if (!line.startsWith('|')) continue;
    const c = splitRow(line);
    detail.set(c[0], { ws: c[1], steps: c[4] ?? '', expect: c[5] ?? '' });
  }
  const mine = open.filter((r) => ownerOf(r.who) !== 'claude');
  const claude = open.filter((r) => ownerOf(r.who) === 'claude');

  const questions = [];
  const qFiles = [path.join(PLANS, 'QUESTIONS.md'), ...readdirSync(path.join(PLANS, 'notes')).filter((f) => /^questions-.+\.md$/.test(f)).sort().map((f) => path.join(PLANS, 'notes', f))];
  const seen = new Set();
  // ids the owner answered in the interview (notes/owner-answers.md, first column) are not open
  const answeredIds = new Set([...read(path.join(PLANS, 'notes/owner-answers.md')).matchAll(/Q-[A-Z]?\d+/g)].map((m) => m[0]));
  const decided = (q) => /owner answer|owner-confirmed|owner confirmed|\bAnswer:|D-0\d\d/i.test(`${q.def} ${q.note}`);
  let decidedCount = 0;
  for (const f of qFiles) for (const q of openQuestions(read(f), path.relative(PLANS, f))) {
    if (seen.has(q.id)) continue;
    seen.add(q.id);
    if (answeredIds.has(q.id) || decided(q)) decidedCount += 1;
    else questions.push(q);
  }

  const missed = openMissed(read(path.join(PLANS, 'MISSED-FEATURES.md')));
  const missedOwner = missed.filter((m) => needsOwner(m.needs));
  const missedDev = missed.filter((m) => !needsOwner(m.needs));

  const L = [];
  const push = (...x) => L.push(...x);
  push('<!-- SPDX-License-Identifier: MIT -->', '<!-- Copyright (c) 2026 commercetools GmbH. Freely available, AS IS and UNSUPPORTED. -->', '', '# Open items, by who acts', '', 'Generated by `node plans/open-items.mjs`; do not edit (edit the source files, then rerun). Sources: `TODO-MANUAL-TESTING.md`, `QUESTIONS.md`, `notes/questions-*.md`, `MISSED-FEATURES.md`. Nothing here is closed by Claude: an owner row closes only with the owner\'s quoted statement (workstream Z, D9).', '');
  push('| Bucket | Count |', '| --- | --- |', `| 1. Owner actions and tests (rows of TODO-MANUAL-TESTING.md) | ${mine.length} |`, `| 2. Owner decisions pending (questions, default in use) | ${questions.length} |`, `| 3. Claude verification waiting on the owner's prerequisites (rows) | ${claude.length} |`, `| 4a. Missed or deferred features that need the owner or a live project | ${missedOwner.length} |`, `| 4b. Missed or deferred features a developer can still build | ${missedDev.length} |`, '');

  push('## 1. Owner actions and tests', '', 'Do the credential and set-up rows first (OA-01, OA-02, OA-05, OA-08 to OA-15): rows in section 3 wait on them.', '', '| Row | Workstream | Action (first sentence of the steps) | Blocks |', '| --- | --- | --- | --- |');
  for (const r of mine) { const d = detail.get(r.id) ?? { ws: '', steps: '' }; push(`| ${r.id} | ${d.ws} | ${clip(d.steps.replace(/^1\)\s*/, ''), 190)} | ${clip(r.when, 70)} |`); }
  push('');

  push('## 2. Owner decisions pending (the default in the question row is used meanwhile)', '', `Questions the owner answered in the interview (\`notes/owner-answers.md\`) or whose default cites an owner answer or a decision (D-nnn) are left out (${decidedCount}). The interview closed with "rest: all other questions keep the default taken in their plan", so every row below is running on its default, accepted in bulk, never individually confirmed. Confirm or change one only when you disagree with its default.`, '', '| Question | Question text | Default in use | Blocks | File |', '| --- | --- | --- | --- | --- |');
  for (const q of questions) push(`| ${q.id}${q.note ? ` (${clip(q.note, 20)})` : ''} | ${clip(q.question, 120)} | ${clip(q.def, 110)} | ${clip(q.blocks, 40)} | ${q.source.replace(/^notes\/questions-|\.md$/g, '')} |`);
  push('');

  push('## 3. Claude verification waiting on prerequisites (no owner effort beyond the prerequisite)', '');
  const groups = new Map();
  for (const r of claude) {
    const pre = [...new Set(`${r.who} ${r.when}`.match(/\b(?:OA|SO)-\d\d\b/g) ?? [])].sort().join(', ') || 'none named (a built workstream or the Chrome MCP)';
    groups.set(pre, [...(groups.get(pre) ?? []), r.id]);
  }
  push('| Waits on | Rows |', '| --- | --- |');
  for (const [k, v] of [...groups].sort((a, b) => b[1].length - a[1].length)) push(`| ${k} | ${v.join(', ')} |`);
  push('');

  push('## 4a. Missed or deferred features that need the owner or a live project', '', '| Workstream | Spec / requirement | What is missing | Needs |', '| --- | --- | --- | --- |');
  for (const m of missedOwner) push(`| ${m.ws} | ${clip(m.spec, 60)} | ${clip(m.what, 140)} | ${clip(m.needs, 70)} |`);
  push('', '## 4b. Missed or deferred features a developer can still build', '', '| Workstream | Spec / requirement | What is missing | Needs |', '| --- | --- | --- | --- |');
  for (const m of missedDev) push(`| ${m.ws} | ${clip(m.spec, 60)} | ${clip(m.what, 140)} | ${clip(m.needs, 70)} |`);
  push('');
  return `${L.join('\n')}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const file = path.join(PLANS, 'OPEN-ITEMS.md');
  const body = build();
  if (process.argv.includes('--check')) {
    const stale = !existsSync(file) || read(file) !== body;
    console.log(stale ? 'open-items: STALE (run node plans/open-items.mjs)' : 'open-items: up to date');
    process.exit(stale ? 1 : 0);
  }
  writeFileSync(file, body);
  console.log(`open-items: wrote plans/OPEN-ITEMS.md (${body.split('\n').length} lines)`);
}
