// node scripts/skills-generate.mjs [--check]
//
// Generates lib/agent/skills/skills.generated.ts from lib/agent/skills/*/SKILL.md (the source of truth, kept byte for byte with
// upstream so they stay diffable). The agent imports the generated module instead of reading the files at runtime: on a bundler-based
// host a file-tracing miss does not fail, it yields an empty registry whose index is baked into the cached static prompt.
// --check fails (exit 1) when the generated module is stale; it is part of `npm run check`.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = join(root, 'lib', 'agent', 'skills');
const outFile = join(skillsDir, 'skills.generated.ts');

const names = readdirSync(skillsDir)
  .filter((n) => statSync(join(skillsDir, n)).isDirectory() && existsSync(join(skillsDir, n, 'SKILL.md')))
  .sort();
if (names.length === 0) {
  console.error('skills-generate: no SKILL.md found under lib/agent/skills');
  process.exit(1);
}

const entries = names.map((name) => ({ path: `${name}/SKILL.md`, text: readFileSync(join(skillsDir, name, 'SKILL.md'), 'utf8') }));
const output =
  `// GENERATED by scripts/skills-generate.mjs from lib/agent/skills/*/SKILL.md. Do not edit; run \`npm run agent:skills\`.\n` +
  `export const SKILL_SOURCES: ReadonlyArray<{ readonly path: string; readonly text: string }> = ${JSON.stringify(entries, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('skills-generate: lib/agent/skills/skills.generated.ts is stale. Run `npm run agent:skills` and commit the result.');
    process.exit(1);
  }
  console.log(`skills-generate: ${names.length} skills, generated module is current`);
} else {
  writeFileSync(outFile, output);
  console.log(`skills-generate: wrote ${names.length} skills to lib/agent/skills/skills.generated.ts`);
}
