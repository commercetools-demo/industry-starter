import 'server-only';
import { getStore } from '@netlify/blobs';
import { type LoadedSession, type SessionStore, type StoredSession, VersionConflict, decodeSession, encodeSession } from './session-store';

/** The slice of the Netlify Blobs `Store` this module uses (so tests can pass a fake). */
export interface BlobStoreLike {
  getWithMetadata(key: string, options: { type: 'text' }): Promise<{ data: string; etag?: string } | null>;
  set(key: string, data: string, options?: { onlyIfMatch?: string; onlyIfNew?: boolean }): Promise<{ modified: boolean; etag?: string }>;
  delete(key: string): Promise<void>;
}

const STORE_NAME = 'assistant-sessions';
// An unguessable id is generated by the session route; this check only keeps a hostile cookie value from becoming an odd blob key.
const KEY = /^[A-Za-z0-9_-]{16,128}$/;

/**
 * Netlify Blobs session store. The etag is the version, and it is the optimistic-concurrency token: `onlyIfMatch` makes a lost race a
 * refused write (`modified: false`), never an overwrite. `strong` consistency so a request on another instance reads the previous turn.
 * Serverless functions cannot rely on any in-process state, which is why this exists.
 */
export class BlobsSessionStore implements SessionStore {
  constructor(private readonly store: BlobStoreLike = getStore({ name: STORE_NAME, consistency: 'strong' }) as unknown as BlobStoreLike) {}

  private key(id: string): string {
    if (!KEY.test(id)) throw new Error('invalid session id');
    return id;
  }

  async get(id: string): Promise<LoadedSession | null> {
    const found = await this.store.getWithMetadata(this.key(id), { type: 'text' });
    if (!found || !found.etag) return null;
    return { session: decodeSession(found.data), version: found.etag };
  }

  async create(session: StoredSession): Promise<string> {
    const result = await this.store.set(this.key(session.id), encodeSession(session), { onlyIfNew: true });
    if (!result.modified || !result.etag) throw new VersionConflict();
    return result.etag;
  }

  async save(session: StoredSession, expectedVersion: string): Promise<string> {
    const result = await this.store.set(this.key(session.id), encodeSession(session), { onlyIfMatch: expectedVersion });
    if (!result.modified || !result.etag) throw new VersionConflict();
    return result.etag;
  }

  async delete(id: string): Promise<void> {
    await this.store.delete(this.key(id));
  }
}
